import { afterEach, describe, expect, it, vi } from "vitest";
import fictionalSnapshot from "../../test-fixtures/linkedin-snapshots/fictional-member.json";
import type { NormalizationInput, NormalizationResult, StationOutcome } from "./contract";
import { adaptLinkedInSnapshot } from "./adapt-linkedin-snapshot";
import { applyExplicitReviewAssertions, type ExplicitReviewUpdates } from "./apply-explicit-review-assertions";
import * as batch from "./normalize-career-batch";
import { validateNormalizationContract } from "./validate";

const missing = { kind: "MISSING" } as const;
const asserted = <T>(value: T) => ({ kind: "ASSERTED", value }) as const;
const organisationId = "00000000-0000-4000-8000-00000000e401";
const programId = "00000000-0000-4000-8000-00000000e402";
const institutionId = "00000000-0000-4000-8000-00000000e403";
const original = () => adaptLinkedInSnapshot(fictionalSnapshot);
const inputError = "Invalid source-neutral review input";
const updateError = "Invalid explicit review assertions";
const resultError = "Review assertions violated normalization contract";
const selection = (entity: "PROGRAM" | "INSTITUTION" | "ORGANISATION", id: string) =>
  ({ identity: { entity, id }, confirmation: "EXPLICIT_SELECTION" }) as const;
function completedMaster(): ExplicitReviewUpdates {
  return { updates: [{ sourceKey: "snapshot:2:0", classification: { type: "DEGREE", level: "MASTER" }, degreeStatus: "COMPLETED", position: 1 }] };
}
function employment(): ExplicitReviewUpdates {
  return { updates: [{ sourceKey: "snapshot:1:0", classification: { type: "CAREER_STEP", careerStepType: "EMPLOYMENT" }, temporalStatus: "ONGOING", position: 4,
    catalogSelection: selection("ORGANISATION", organisationId) }] };
}
function review(sourceKey: string, field: "classification" | "position" | "endYear" | "catalogAssociation" | "status" | "temporalStatus", reason: "CLASSIFICATION_UNCERTAIN" | "MISSING" | "CONFLICTING_FACTS"): StationOutcome {
  return { sourceKey, kind: "REVIEW_REQUIRED", unresolved: [{ field, reason }] };
}
// Independently authored expectations. No oracle or expected canonical value is
// generated by the batch normalizer, adapter or review overlay.
function expectedMaster(): StationOutcome {
  return { sourceKey: "snapshot:2:0", kind: "RESOLVED_DEGREE", position: 1,
    canonical: { level: "MASTER", status: "COMPLETED", title: "Synthetic M.Sc.", fieldOfStudy: null,
      startYear: 2019, endYear: 2022, graduationYear: null, programId: null, institutionId: null },
    unresolved: [{ field: "graduationYear", reason: "MISSING" }, { field: "catalogAssociation", reason: "UNKNOWN" }] };
}
function expectedEmployment(): StationOutcome {
  return { sourceKey: "snapshot:1:0", kind: "RESOLVED_CAREER_STEP", position: 4,
    canonical: { type: "EMPLOYMENT", temporalStatus: "ONGOING", roleTitle: "Synthetic Research Assistant",
      roleCategory: null, functionArea: null, location: null, startYear: 2023, endYear: null, organisationId },
    unresolved: [{ field: "endYear", reason: "MISSING" }] };
}
function overlay(input: NormalizationInput, updates: unknown) {
  const before = structuredClone(input), updatesBefore = structuredClone(updates);
  const enriched = applyExplicitReviewAssertions(input, updates);
  const result = batch.normalizeCareerBatch(enriched);
  expect(validateNormalizationContract(enriched, result)).toEqual({ ok: true, diagnostics: [] });
  expect(input).toEqual(before); expect(updates).toEqual(updatesBefore);
  expect(enriched.stations.map(s => s.key)).toEqual(input.stations.map(s => s.key));
  for (const [index, station] of enriched.stations.entries()) {
    for (const field of ["title", "category", "providerLabel", "start", "end", "graduation"] as const) {
      expect(station[field]).toEqual(input.stations[index][field]);
    }
  }
  for (const outcome of result.stations) {
    if (outcome.kind === "REVIEW_REQUIRED") expect(Object.keys(outcome).sort()).toEqual(["kind", "sourceKey", "unresolved"]);
  }
  return { enriched, result };
}
function expectRejected(input: unknown, updates: unknown, message = updateError) {
  const before = structuredClone(input), updatesBefore = structuredClone(updates);
  for (let attempt = 0; attempt < 2; attempt++) {
    expect(() => applyExplicitReviewAssertions(input as NormalizationInput, updates)).toThrow(new Error(message));
  }
  expect(input).toEqual(before); expect(updates).toEqual(updatesBefore);
}
afterEach(() => vi.restoreAllMocks());

describe("E.4b.1 explicit review assertion overlay", () => {
  it("resolves explicitly reviewed Master and employment, retaining null graduation and unreviewed sources", () => {
    const updates: ExplicitReviewUpdates = { updates: [...completedMaster().updates, ...employment().updates] };
    const { enriched, result } = overlay(original(), updates);
    expect(enriched.stations[2].classification).toEqual(asserted({ type: "DEGREE", level: "MASTER" }));
    expect(enriched.stations[2].degreeStatus).toEqual(asserted("COMPLETED"));
    expect(enriched.stations[0].temporalStatus).toEqual(asserted("ONGOING"));
    expect(enriched.stations[0].catalog).toEqual({ kind: "CONFIRMED", ...selection("ORGANISATION", organisationId) });
    expect(result).toEqual({ stations: [expectedEmployment(), review("snapshot:1:1", "classification", "CLASSIFICATION_UNCERTAIN"),
      expectedMaster(), review("snapshot:2:1", "classification", "CLASSIFICATION_UNCERTAIN")] });
    expect(enriched.stations[1]).toEqual(original().stations[1]);
    expect(enriched.stations[3]).toEqual(original().stations[3]);
    expect(enriched.stations[2].graduation).toEqual(missing);
  });
  it("preserves unknown catalog and missing status without inferring ONGOING from an empty end", () => {
    const { enriched, result } = overlay(original(), { updates: [{ sourceKey: "snapshot:1:0", classification: { type: "CAREER_STEP", careerStepType: "EMPLOYMENT" }, position: 7 }] });
    expect(enriched.stations[0].catalog).toEqual({ kind: "UNKNOWN" });
    expect(enriched.stations[0].temporalStatus).toEqual(missing);
    expect(result.stations[0]).toEqual({ sourceKey: "snapshot:1:0", kind: "RESOLVED_CAREER_STEP", position: 7,
      canonical: { type: "EMPLOYMENT", temporalStatus: "UNKNOWN", roleTitle: "Synthetic Research Assistant",
        roleCategory: null, functionArea: null, location: null, startYear: 2023, endYear: null, organisationId: null },
      unresolved: [{ field: "temporalStatus", reason: "MISSING" }, { field: "endYear", reason: "MISSING" }, { field: "catalogAssociation", reason: "UNKNOWN" }] });
  });
  it("withholds observed end for unknown status rather than silently asserting ENDED", () => {
    const { result } = overlay(original(), { updates: [{ sourceKey: "snapshot:1:1", classification: { type: "CAREER_STEP", careerStepType: "INTERNSHIP" }, position: 2 }] });
    expect(result.stations[1]).toEqual({ sourceKey: "snapshot:1:1", kind: "RESOLVED_CAREER_STEP", position: 2,
      canonical: { type: "INTERNSHIP", temporalStatus: "UNKNOWN", roleTitle: "Synthetic Internship",
        roleCategory: null, functionArea: null, location: null, startYear: 2019, endYear: null, organisationId: null },
      unresolved: [{ field: "temporalStatus", reason: "MISSING" }, { field: "endYear", reason: "STATUS_UNCERTAIN" }, { field: "catalogAssociation", reason: "UNKNOWN" }] });
  });
  it("retains contradictory ONGOING and supplied end evidence for target-free review", () => {
    const { enriched, result } = overlay(original(), { updates: [{ sourceKey: "snapshot:1:1", classification: { type: "CAREER_STEP", careerStepType: "EMPLOYMENT" }, temporalStatus: "ONGOING", position: 2 }] });
    expect(enriched.stations[1].temporalStatus).toEqual(asserted("ONGOING"));
    expect(enriched.stations[1].end).toEqual({ kind: "OBSERVED", value: { precision: "MONTH", month: 2, year: 2020 } });
    expect(result.stations[1]).toEqual(review("snapshot:1:1", "endYear", "CONFLICTING_FACTS"));
  });
  it.each(["PROGRAM", "INSTITUTION"] as const)("keeps explicit %s selection incompatible with CareerStep as review", entity => {
    const updates = employment(); updates.updates[0].catalogSelection = selection(entity, entity === "PROGRAM" ? programId : institutionId);
    const { enriched, result } = overlay(original(), updates);
    expect(enriched.stations[0].catalog).toEqual({ kind: "CONFIRMED", ...updates.updates[0].catalogSelection });
    expect(result.stations[0]).toEqual(review("snapshot:1:0", "catalogAssociation", "CONFLICTING_FACTS"));
  });
  it.each(["PROGRAM", "INSTITUTION"] as const)("allows explicit %s selection for Degree without name matching", entity => {
    const updates = completedMaster(); updates.updates[0].catalogSelection = selection(entity, entity === "PROGRAM" ? programId : institutionId);
    const { result } = overlay(original(), updates);
    const expected = expectedMaster();
    if (expected.kind !== "RESOLVED_DEGREE") throw new Error("Invalid authored test expectation");
    expected.canonical = { ...expected.canonical, ...(entity === "PROGRAM" ? { programId, institutionId: null } : { programId: null, institutionId }) };
    expected.unresolved = [{ field: "graduationYear", reason: "MISSING" }];
    expect(result.stations[2]).toEqual(expected);
  });
  it("does not promote CANDIDATE without a separate explicit selection", () => {
    const input = original(); input.stations[0].catalog = { kind: "CANDIDATE", identity: { entity: "ORGANISATION", id: organisationId }, basis: "NAME_MATCH" };
    const updates = employment(); delete updates.updates[0].catalogSelection;
    const { enriched, result } = overlay(input, updates);
    expect(enriched.stations[0].catalog).toEqual(input.stations[0].catalog);
    expect(result.stations[0]).toMatchObject({ canonical: { organisationId: null }, unresolved: [
      { field: "endYear", reason: "MISSING" }, { field: "catalogAssociation", reason: "CATALOG_UNCONFIRMED" },
    ] });
    expect(overlay(input, employment()).enriched.stations[0].catalog).toEqual({ kind: "CONFIRMED", ...selection("ORGANISATION", organisationId) });
  });
  it("permits an explicit selection different from a supplied candidate without copying candidate identity", () => {
    const input = original(); input.stations[0].catalog = { kind: "CANDIDATE", identity: { entity: "PROGRAM", id: programId }, basis: "SUPPLIED_CANDIDATE" };
    expect(overlay(input, employment()).result.stations[0]).toEqual(expectedEmployment());
  });
  it("retains partial classification review when only status or only position is asserted", () => {
    for (const partial of [{ temporalStatus: "ONGOING" }, { position: 4 }]) {
      const { result } = overlay(original(), { updates: [{ sourceKey: "snapshot:1:0", ...partial }] });
      expect(result.stations[0]).toEqual(review("snapshot:1:0", "classification", "CLASSIFICATION_UNCERTAIN"));
    }
  });
  it("does not fabricate position from a classification-only update", () => {
    const { result } = overlay(original(), { updates: [{ sourceKey: "snapshot:2:0", classification: { type: "DEGREE", level: "MASTER" } }] });
    expect(result.stations[2]).toEqual(review("snapshot:2:0", "position", "MISSING"));
  });
  it("retains missing Degree status and withheld attendance end after incomplete review", () => {
    const { result } = overlay(original(), { updates: [{ sourceKey: "snapshot:2:0", classification: { type: "DEGREE", level: "MASTER" }, position: 1 }] });
    expect(result.stations[2]).toEqual({ sourceKey: "snapshot:2:0", kind: "RESOLVED_DEGREE", position: 1,
      canonical: { level: "MASTER", status: "UNKNOWN", title: "Synthetic M.Sc.", fieldOfStudy: null,
        startYear: 2019, endYear: null, graduationYear: null, programId: null, institutionId: null },
      unresolved: [{ field: "status", reason: "MISSING" }, { field: "endYear", reason: "STATUS_UNCERTAIN" },
        { field: "graduationYear", reason: "MISSING" }, { field: "catalogAssociation", reason: "UNKNOWN" }] });
  });
  it.each([
    { classification: { type: "DEGREE", level: "MASTER" }, temporalStatus: "UNKNOWN", expectedField: "temporalStatus" },
    { classification: { type: "CAREER_STEP", careerStepType: "EMPLOYMENT" }, degreeStatus: "UNKNOWN", expectedField: "status" },
  ] as const)("preserves cross-kind assertions for review: $expectedField", ({ expectedField, ...facts }) => {
    const { result } = overlay(original(), { updates: [{ sourceKey: "snapshot:1:0", position: 1, ...facts }] });
    expect(result.stations[0]).toEqual(review("snapshot:1:0", expectedField, "CONFLICTING_FACTS"));
  });
  it("fills UNKNOWN absence markers but does not treat labels or indexes as review evidence", () => {
    const input = original();
    input.stations[0].classification = { kind: "UNKNOWN", origin: "OBSERVED" };
    input.stations[0].temporalStatus = { kind: "UNKNOWN", origin: "ASSERTED" };
    input.stations[0].position = { kind: "UNKNOWN", origin: "ASSERTED" };
    expect(overlay(input, employment()).result.stations[0]).toEqual(expectedEmployment());
  });
  it("accepts a no-op envelope and empty input while returning detached values", () => {
    const input = original(); const { enriched } = overlay(input, { updates: [] });
    expect(enriched).toEqual(input); expect(enriched).not.toBe(input); expect(enriched.stations[0]).not.toBe(input.stations[0]);
    expect(overlay({ stations: [] }, { updates: [] }).enriched).toEqual({ stations: [] });
  });
  it("preserves input order, gaps and determinism regardless of review update order", () => {
    const updates = { updates: [...completedMaster().updates, ...employment().updates] };
    const first = overlay(original(), updates);
    expect(overlay(original(), { updates: [...updates.updates].reverse() })).toEqual(first);
    expect(first.result.stations.map(s => s.sourceKey)).toEqual(["snapshot:1:0", "snapshot:1:1", "snapshot:2:0", "snapshot:2:1"]);
    expect(first.result.stations.map(s => s.kind === "REVIEW_REQUIRED" ? null : s.position)).toEqual([4, null, 1, null]);
  });
  it("supports frozen inputs/updates and retains no mutable aliases to either", () => {
    const input = original(), updates = employment(); const before = structuredClone({ input, updates });
    function freeze(v: unknown) { if (v !== null && typeof v === "object") { Object.values(v).forEach(freeze); Object.freeze(v); } }
    freeze(input); freeze(updates);
    const { enriched } = overlay(input, updates);
    enriched.stations[0].classification = asserted({ type: "DEGREE", level: "PHD" });
    if (enriched.stations[0].catalog.kind === "CONFIRMED") enriched.stations[0].catalog.identity.id = programId;
    if (enriched.stations[2].start.kind === "OBSERVED" && enriched.stations[2].start.value.precision === "YEAR") enriched.stations[2].start.value.year = 2001;
    expect({ input, updates }).toEqual(before);
    expect(overlay(input, updates).result.stations[0]).toEqual(expectedEmployment());
  });
  it("preserves independently supplied graduation and observed uncertainty facts without revising them", () => {
    const input = original(); input.stations[2].graduation = asserted({ precision: "YEAR", year: 2022 });
    input.stations[2].providerLabel = { kind: "UNKNOWN", origin: "OBSERVED" };
    const expected = expectedMaster();
    if (expected.kind !== "RESOLVED_DEGREE") throw new Error("Invalid authored test expectation");
    expected.canonical.graduationYear = 2022; expected.unresolved = [{ field: "catalogAssociation", reason: "UNKNOWN" }];
    expect(overlay(input, completedMaster()).result.stations[2]).toEqual(expected);
  });

  const malformedUpdates: [string, unknown][] = [
    ["null", null], ["undefined", undefined], ["array root", []], ["primitive", "fictional-private-envelope"], ["missing updates", {}],
    ["null updates", { updates: null }], ["object updates", { updates: {} }], ["sparse entries", { updates: Array(1) }],
    ["null entry", { updates: [null] }], ["array entry", { updates: [[]] }],
    ["extra envelope key", { updates: [], private: "fictional-private-field" }],
    ["no assertion", { updates: [{ sourceKey: "snapshot:1:0" }] }], ["no sourceKey", { updates: [{ position: 1 }] }],
    ["unknown sourceKey", { updates: [{ sourceKey: "fictional-private-unrecognized-key", position: 1 }] }],
    ["padded sourceKey", { updates: [{ sourceKey: " snapshot:1:0", position: 1 }] }],
    ["duplicate sourceKey", { updates: [{ sourceKey: "snapshot:1:0", position: 1 }, { sourceKey: "snapshot:1:0", temporalStatus: "ONGOING" }] }],
    ["wrapped classification", { updates: [{ sourceKey: "snapshot:1:0", classification: asserted({ type: "DEGREE", level: "MASTER" }) }] }],
  ];
  it.each(malformedUpdates)("rejects malformed update envelope: %s", (_, updates) => expectRejected(original(), updates));
  it.each([
    { classification: { type: "DEGREE" } }, { classification: { type: "DEGREE", level: "MSC" } },
    { classification: { type: "CAREER_STEP" } }, { classification: { type: "CAREER_STEP", careerStepType: "POSITION" } },
    { classification: { type: "DEGREE", level: "MASTER", private: "fictional-private-classification" } },
    { degreeStatus: "AWARDED" }, { degreeStatus: null }, { temporalStatus: "CURRENT" }, { temporalStatus: undefined },
    { classification: missing }, { degreeStatus: asserted("COMPLETED") },
    { classification: undefined, position: 1 },
  ])("rejects invalid assertion payload: %j", facts => expectRejected(original(), { updates: [{ sourceKey: "snapshot:1:0", ...facts }] }));
  it.each([0, -1, 1.5, "1", null, undefined, Number.NaN, Number.POSITIVE_INFINITY, Number.MAX_SAFE_INTEGER + 1])(
    "rejects invalid timeline position %j", position => expectRejected(original(), { updates: [{ sourceKey: "snapshot:1:0", position }] }));
  it.each([
    null, {}, { identity: { entity: "ORGANISATION", id: organisationId } },
    { ...selection("ORGANISATION", organisationId), confirmation: "TRUSTED_INPUT" },
    { ...selection("ORGANISATION", organisationId), extra: "fictional-private-catalog" },
    { identity: { entity: "COMPANY", id: organisationId }, confirmation: "EXPLICIT_SELECTION" },
    selection("ORGANISATION", "fictional-private-invalid-uuid"), selection("ORGANISATION", ` ${organisationId}`),
    { identity: { entity: "ORGANISATION", id: organisationId, name: "Fictional Label" }, confirmation: "EXPLICIT_SELECTION" },
  ])("rejects malformed or non-explicit catalog selection: %j", catalogSelection => expectRejected(original(), { updates: [{ sourceKey: "snapshot:1:0", catalogSelection }] }));
  it.each(["title", "category", "providerLabel", "start", "end", "graduation", "key", "catalog", "canonical", "referenceDegreeId"])(
    "rejects forbidden replacement field %s even alongside a valid assertion", field => {
      expectRejected(original(), { updates: [{ sourceKey: "snapshot:1:0", position: 1, [field]: "fictional-private-replacement" }] });
    });
  it("rejects a full SourceStation replacement and fails atomically after an earlier valid update", () => {
    expectRejected(original(), { updates: [{ ...original().stations[0], sourceKey: "snapshot:1:0" }] });
    expectRejected(original(), { updates: [...completedMaster().updates, { sourceKey: "snapshot:1:0", title: "Fictional replacement", position: 4 }] });
  });
  it.each([
    { field: "classification", old: { type: "DEGREE", level: "MASTER" }, next: { type: "CAREER_STEP", careerStepType: "EMPLOYMENT" } },
    { field: "degreeStatus", old: "UNKNOWN", next: "COMPLETED" },
    { field: "temporalStatus", old: "UNKNOWN", next: "ONGOING" }, { field: "position", old: 4, next: 1 },
  ])("rejects revision or replay of existing asserted $field", ({ field, old, next }) => {
    const input = original(); Object.assign(input.stations[0], { [field]: asserted(old) });
    for (const value of [old, next]) expectRejected(input, { updates: [{ sourceKey: "snapshot:1:0", [field]: value }] });
  });
  it.each(["EXPLICIT_SELECTION", "TRUSTED_INPUT"] as const)("preserves existing %s catalog identity and rejects reselection", confirmation => {
    const input = original(); input.stations[0].catalog = { kind: "CONFIRMED", identity: { entity: "ORGANISATION", id: organisationId }, confirmation };
    for (const identity of [selection("ORGANISATION", organisationId), selection("PROGRAM", programId)]) {
      expectRejected(input, { updates: [{ sourceKey: "snapshot:1:0", catalogSelection: identity }] });
    }
    expect(overlay(input, { updates: [{ sourceKey: "snapshot:1:0", position: 4 }] }).enriched.stations[0].catalog).toEqual(input.stations[0].catalog);
  });
  it("allows later addition of missing fields without revising previous assertions", () => {
    const first = overlay(original(), { updates: [{ sourceKey: "snapshot:2:0", classification: { type: "DEGREE", level: "MASTER" } }] }).enriched;
    expect(overlay(first, { updates: [{ sourceKey: "snapshot:2:0", degreeStatus: "COMPLETED", position: 1 }] }).result.stations[2]).toEqual(expectedMaster());
  });
  it("rejects duplicate asserted positions even when both stations lack classification", () => {
    expectRejected(original(), { updates: [{ sourceKey: "snapshot:1:0", position: 3 }, { sourceKey: "snapshot:2:0", position: 3 }] }, resultError);
  });
  it("rejects position collision with an unchanged station still requiring review", () => {
    const input = original(); input.stations[1].position = asserted(4);
    expectRejected(input, employment(), resultError);
  });
  it("rejects duplicate positions in a fully resolved batch without renumbering", () => {
    const updates = completedMaster(); updates.updates[0].position = 4;
    expectRejected(original(), { updates: [...updates.updates, ...employment().updates] }, resultError);
  });
  it("rejects pre-existing duplicate asserted positions even for a no-op update", () => {
    const input = original(); input.stations[0].position = asserted(2); input.stations[1].position = asserted(2);
    expectRejected(input, { updates: [] }, resultError);
  });
  const malformedInputs: [string, unknown][] = [
    ["null", null], ["undefined", undefined], ["array", []], ["root", {}], ["stations", { stations: null }],
    ["sparse", { stations: Array(1) }], ["bad station", { stations: [null] }],
    ["extra source field", { stations: [{ ...original().stations[0], profile: "fictional-private-profile" }] }],
    ["duplicate source keys", { stations: [original().stations[0], original().stations[0]] }],
  ];
  it.each(malformedInputs)("rejects invalid original E.1 input before overlay: %s", (_, input) => expectRejected(input, { updates: [] }, inputError));
  it("redacts downstream exceptions without returning partial input or logging", () => {
    const logs = [vi.spyOn(console, "log"), vi.spyOn(console, "warn"), vi.spyOn(console, "error")];
    vi.spyOn(batch, "normalizeCareerBatch").mockImplementation(() => { throw new Error("fictional-private-key / Synthetic University / private-id"); });
    expectRejected(original(), completedMaster(), resultError);
    for (const log of logs) expect(log).not.toHaveBeenCalled();
  });
  it("rejects an invalid returned batch rather than trusting its shape", () => {
    vi.spyOn(batch, "normalizeCareerBatch").mockReturnValue({ stations: [] } satisfies NormalizationResult);
    expectRejected(original(), completedMaster(), resultError);
  });
});
